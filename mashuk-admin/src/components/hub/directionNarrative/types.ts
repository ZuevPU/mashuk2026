/** Родительный падеж названий направлений для шаблонов выводов. */
export const DIR_GENITIVE: Record<string, string> = {
  Учителя: 'Учителей',
  Флагманы: 'Флагманов',
  Навигаторы: 'Навигаторов',
  Вожатые: 'Вожатых',
  Защитники: 'Защитников',
  Воспитатели: 'Воспитателей',
  Проводники: 'Проводников',
};

export function genitive(dir: string): string {
  return DIR_GENITIVE[dir] || dir;
}
