export type RuRegion = (typeof RU_REGIONS)[number];

const REGION_SET = new Set<string>(RU_REGIONS);

/** Fold punctuation/spaces for fuzzy matching of free-text historical values. */
export function regionKey(raw: string): string {
  return String(raw ?? '')
    .trim()
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[.]+$/g, '')
    .replace(/[\u00a0\u202f]/g, ' ')
    .replace(/[\u2010-\u2015\u2212‑–—−]/g, '-')
    .replace(/\s+/g, ' ')
    .replace(/\s*-\s*/g, '-')
    .trim();
}

const CANON_BY_KEY = new Map<string, string>();
for (const name of RU_REGIONS) {
  CANON_BY_KEY.set(regionKey(name), name);
}

