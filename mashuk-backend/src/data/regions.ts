export function isCanonicalRegion(value: string): boolean {
  return REGION_SET.has(value);
}

/**
 * Map free text to a canonical region when possible; otherwise keep trimmed custom value
 * (foreign / «Иное»).
 */
export function normalizeRegion(raw: unknown): string {
  const text = String(raw ?? '').trim().replace(/\s+/g, ' ').slice(0, 255);
  if (!text) return '';
  if (REGION_SET.has(text)) return text;
  const mapped = CANON_BY_KEY.get(regionKey(text));
  return mapped || text;
}
